"""Copy ONLY the project-owned local edit package into an existing Comfy root.

Usage: python worker/install_local_edit_nodes.py --comfy-root <ComfyRoot>
No pip, model downloads, plugin changes, service checks, or restarts. A hash
ledger permits idempotent updates of our unmodified files; an unfamiliar or
locally edited destination is refused before any package file is overwritten.
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil

PACKAGE_NAME = "chouka_local_edit"
LEDGER_NAME = ".chouka-local-edit-owned.json"
PACKAGE_FILES = ("__init__.py", "geometry.py", "cloud.py")


def _digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def install(comfy_root):
    root = Path(comfy_root).absolute()
    if not (root / "main.py").is_file() or not (root / "custom_nodes").is_dir():
        raise ValueError("--comfy-root must contain main.py and an existing custom_nodes directory")
    source = Path(__file__).resolve().parents[1] / "comfy_nodes" / PACKAGE_NAME
    for name in PACKAGE_FILES:
        if not (source / name).is_file() or (source / name).is_symlink():
            raise ValueError("project local edit package is incomplete")
    target = root / "custom_nodes" / PACKAGE_NAME
    if target.is_symlink() or (target.exists() and not target.is_dir()):
        raise ValueError("refusing a linked or non-directory destination")
    previous = {}
    ledger = target / LEDGER_NAME
    if target.exists():
        entries = list(target.iterdir())
        if entries:
            if ledger.is_symlink() or not ledger.is_file():
                raise ValueError("destination is not a managed package; refusing to overwrite user files")
            try:
                record = json.loads(ledger.read_text(encoding="utf-8"))
                previous = record["files"]
                if (record["owner"] != PACKAGE_NAME or record["version"] != 1
                        or not isinstance(previous, dict) or set(previous) != set(PACKAGE_FILES)
                        or any(not isinstance(v, str) or len(v) != 64 for v in previous.values())):
                    raise ValueError
            except (ValueError, KeyError, TypeError):
                raise ValueError("invalid ownership ledger; refusing to overwrite destination") from None
            for entry in entries:
                if entry.is_symlink():
                    raise ValueError("refusing linked destination entries")
                if entry.name == "__pycache__" and entry.is_dir():
                    continue  # generated by Comfy, never copied, deleted, or changed here
                if entry.name not in (*PACKAGE_FILES, LEDGER_NAME) or not entry.is_file():
                    raise ValueError("unfamiliar destination files; refusing to overwrite user package")
            for name, digest in previous.items():
                if not (target / name).is_file() or _digest(target / name) != digest:
                    raise ValueError("destination was locally modified; back it up before installing")
    hashes = {name: _digest(source / name) for name in PACKAGE_FILES}
    if previous == hashes:
        return target
    target.mkdir(exist_ok=True)
    for name in PACKAGE_FILES:
        if previous.get(name) != hashes[name]:
            shutil.copy2(source / name, target / name)
    ledger.write_text(json.dumps({"owner": PACKAGE_NAME, "version": 1, "files": hashes},
                                 indent=2) + "\n", encoding="utf-8")
    return target


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--comfy-root", required=True)
    args = parser.parse_args(argv)
    try:
        target = install(args.comfy_root)
    except (ValueError, OSError) as exc:
        parser.exit(1, f"Local edit node install refused: {exc}\n")
    print(f"Local edit nodes ready at {target}. No service was restarted.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
