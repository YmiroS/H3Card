- 烟雾通过形态变化、扩散、混合与浓淡变化表现，不保持刚性团块轮廓或像布条反复回摆；局部涡动要有流动依据，不为“自然”添加无穷旋涡。
- 人物或物体穿过时，只有足够的相对运动才强调附近的局部扰动与尾流；不让普通挥手切出永久清空的通道，不让整片远处雾层同步弹开。
- 单次扬尘可随输运扩散而逐渐变淡，较易沉降的颗粒在相应时间尺度落下；不能要求所有烟雾像沙粒沉地，也不能让仍有强供给的烟源在动作结束时突然完全消失。
