- 落地后可短暂滑动、滚动或有限反弹，逐渐受摩擦和碰撞耗散；持续斜坡或外力存在时可继续运动，不强行在平地外停止。处于承托或滑动阶段时与支撑面接触；已有反弹腾空阶段不强制贴地，不出现无依据的漂浮或穿透。
