- 色彩：成组色块与相邻关系建立气氛，不对每个对象单独加饱和。
- 边缘：焦点与关键连接较明确，次要边缘可以合并或在环境中隐去。
- 材质：保留足以区分材料的反射与厚薄，减少无关微纹，而非全场塑料。
