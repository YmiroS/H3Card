先判断源图的可靠程度和用户要求的匹配精度。可靠灰模或明确逐点复现适用下述投影保持；粗稿自然化只保留可靠布局、动作意图与关系，可校正明显笔误。逐点锚定不能凌驾于已要求的自然解剖、角色设计比例与共同相机之上；若用户同时明确锁死相互矛盾的项目，指出具体冲突再取舍。

