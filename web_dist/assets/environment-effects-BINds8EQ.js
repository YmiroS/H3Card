对当前效果按需确定来源、触发条件、所选阶段、空间体积、运动趋势、受光、环境反馈与构图职责。无需逐项输出表格，但决定成败的信息应写入最终提示词。静帧选一个可成立的状态；视频需求再描述相邻阶段与连续性，不把时间线塞进单张图。

